const { execFile } = require("child_process");
const fs = require("fs");
const path = require("path");
const { getProviderStatus } = require("../scripts/ai-runner-lib");
const { parseRunnerJson } = require("./utils");
const { createRunnerHealthTracker } = require("./runner-health");

function getRunnerConfig() {
  const providerStatus = getProviderStatus();
  return {
    providerStatus,
    runner: process.env.SUGGESTION_ACTION_RUNNER_SCRIPT || (providerStatus.mode === "openai-compatible" ? "scripts/ai-suggestion-runner.js" : "scripts/codex-suggestion-runner.js"),
    allowFallback: process.env.SUGGESTION_ACTION_ALLOW_FALLBACK === "1",
  };
}

function getStaticRunnerStatus() {
  const runnerConfig = getRunnerConfig();
  return {
    configured: Boolean(runnerConfig.runner),
    runnerScript: runnerConfig.runner,
    runnerScriptExists: Boolean(runnerConfig.runner && fs.existsSync(path.resolve(process.cwd(), runnerConfig.runner))),
    provider: runnerConfig.providerStatus.provider,
    mode: runnerConfig.providerStatus.mode,
    providerMode: runnerConfig.providerStatus.mode,
    model: runnerConfig.providerStatus.model || "",
    allowFallback: runnerConfig.allowFallback,
    apiKeyConfigured: runnerConfig.providerStatus.apiKeyConfigured,
    baseUrlConfigured: runnerConfig.providerStatus.baseUrlConfigured,
    codexRunnable: runnerConfig.providerStatus.codexRunnable,
    codexDetail: runnerConfig.providerStatus.codexDetail || "",
    promptVersion: "agent-suggestion-v1",
    skillPath: "legal-work-orchestrator",
    downstreamSkill: "legal-contract-orchestrator",
  };
}

const runnerHealth = createRunnerHealthTracker("Suggestion action runner", getStaticRunnerStatus);

function getRunnerStatus() {
  return runnerHealth.getStatus();
}

function runSuggestionAction(request) {
  const runnerConfig = getRunnerConfig();
  const startedAt = Date.now();
  runnerHealth.startRun();
  return runConfiguredSuggestionAction(request, runnerConfig).catch((error) => {
    if (!runnerConfig.allowFallback) {
      runnerHealth.markFailure({
        error: error.message || String(error),
        durationMs: Date.now() - startedAt,
        source: path.basename(runnerConfig.runner || ""),
      });
      throw new Error(`AI suggestion action failed: ${error.message || String(error)}`);
    }
    const result = {
      ok: true,
      source: "backend-fallback",
      fallbackReason: error.message || String(error),
      fallbackWarning: "Result was generated by local fallback and was not confirmed by the AI backend.",
      promptVersion: "agent-suggestion-v1",
      skillPath: "legal-work-orchestrator",
      downstreamSkill: "legal-contract-orchestrator",
      ...buildFallbackSuggestionAction(request),
    };
    runnerHealth.markFallback({
      error: error.message || String(error),
      fallbackReason: result.fallbackReason,
      durationMs: Date.now() - startedAt,
      source: result.source,
    });
    return result;
  }).then((result) => {
    if (result?.source !== "backend-fallback") {
      runnerHealth.markSuccess({
        durationMs: Date.now() - startedAt,
        source: result?.source || path.basename(runnerConfig.runner || ""),
      });
    }
    return result;
  });
}

function runConfiguredSuggestionAction(request, runnerConfig = getRunnerConfig()) {
  return new Promise((resolve, reject) => {
    const runnerPath = path.resolve(process.cwd(), runnerConfig.runner);
    const child = execFile(process.execPath, [runnerPath], { maxBuffer: 20 * 1024 * 1024 }, (error, stdout, stderr) => {
      if (error) {
        reject(new Error(`${error.message}\n${stderr || ""}`.trim()));
        return;
      }
      try {
        resolve({
          ok: true,
          source: path.basename(runnerConfig.runner),
          promptVersion: "agent-suggestion-v1",
          skillPath: "legal-work-orchestrator",
          downstreamSkill: "legal-contract-orchestrator",
          ...parseRunnerJson(stdout),
        });
      } catch (parseError) {
        reject(parseError);
      }
    });
    if (child.stdin && typeof child.stdin.on === "function") child.stdin.on("error", () => {});
    child.stdin.write(JSON.stringify(request, null, 2));
    child.stdin.end();
  });
}

function buildFallbackSuggestionAction(request = {}) {
  const suggestion = request.suggestion || {};
  const userAction = request.userAction || "adopt";
  const actionType = normalizeActionType(suggestion.actionType || suggestion.action || "");
  const targetClause = request.targetClause || {};
  const fix = suggestion.fix || suggestion.proposedClauseText || suggestion.proposedRevision || suggestion.issue || "";

  if (userAction === "reject") {
    return {
      action: emptyAction({
        status: "rejected",
        targetClauseId: targetClause.id || request.targetClauseId || "",
        actionType: "none",
        comment: `拒绝 AI 建议：${fix || suggestion.title || "未提供具体原因"}`,
        rejectionReason: fix || suggestion.issue || suggestion.title || "用户已拒绝该 AI 建议。",
        knowledgeNote: "该建议已被拒绝，后续复用时应谨慎人工复核。",
      }),
    };
  }

  if (["comment_only", "business_confirmed"].includes(userAction)) {
    return {
      action: emptyAction({
        status: userAction,
        targetClauseId: targetClause.id || request.targetClauseId || "",
        actionType: "comment_only",
        comment: `${userAction === "business_confirmed" ? "业务已确认" : "仅保留批注"}：${fix || suggestion.issue || ""}`,
        knowledgeNote: "该建议未直接改写合同文本，仅保留说明或确认结果。",
      }),
    };
  }

  if (actionType === "add_clause") {
    return {
      action: emptyAction({
        status: userAction === "adjust" ? "adjusted" : "adopted",
        targetClauseId: targetClause.id || request.targetClauseId || "",
        matchConfidence: 60,
        actionType,
        insertedClause: {
          title: suggestion.title || "New clause",
          type: suggestion.clauseType || targetClause.type || "other",
          text: fix,
          position: "after",
          targetClauseId: targetClause.id || request.targetClauseId || "",
        },
        comment: `采纳 AI 新增条款建议：${suggestion.issue || suggestion.title || ""}`,
        knowledgeNote: "该建议已转换为候选新增条款。",
      }),
    };
  }

  return {
    action: emptyAction({
      status: userAction === "adjust" ? "adjusted" : "adopted",
      targetClauseId: targetClause.id || request.targetClauseId || "",
      matchConfidence: 60,
      actionType,
      editedText: actionType === "delete_clause" ? "" : buildEditedText(targetClause.text || "", fix),
      comment: `采纳 AI ${actionType === "delete_clause" ? "删除" : "修改"}建议：${fix}`,
      knowledgeNote: "该建议已转换为条款动作。",
    }),
  };
}

function emptyAction(overrides = {}) {
  return {
    status: "adopted",
    targetClauseId: "",
    matchConfidence: 0,
    actionType: "none",
    editedText: "",
    insertedClause: { title: "", type: "", text: "", position: "none", targetClauseId: "" },
    comment: "",
    rejectionReason: "",
    knowledgeNote: "",
    ...overrides,
  };
}

function normalizeActionType(value) {
  if (value === "新增") return "add_clause";
  if (value === "删除") return "delete_clause";
  if (["add_clause", "replace_clause", "revise_clause", "delete_clause", "comment_only"].includes(value)) return value;
  return "revise_clause";
}

function buildEditedText(originalText, fix) {
  const clean = String(fix || "").trim();
  if (!clean) return originalText;
  const replacement = clean.match(/^建议修改为[:：]\s*\n?([\s\S]+)$/)?.[1]?.trim();
  if (replacement) return replacement;
  if (/^(第[一二三四五六七八九十百零〇两0-9]+条|[0-9]+[.、)]|\d+(?:\.\d+)+)/.test(clean)) return clean;
  return `${originalText}\n\n【AI修改建议】${clean}`;
}

module.exports = { runSuggestionAction, getRunnerStatus, buildFallbackSuggestionAction, emptyAction, normalizeActionType, buildEditedText, _resetRunnerStatusForTesting: () => runnerHealth.resetForTesting() };
